//! The authorization seam (design requirement Z13).
//!
//! Every operation the server performs on behalf of a caller goes through
//! [`Authorizer::authorize`]: request handlers, listings (once per item
//! returned) and event delivery in the long-poll and the stream (once per
//! event). Nothing else in the crate decides who may do what.
//!
//! A local board has one principal, the local one, and it holds `all`, so
//! [`LocalPolicy`] allows everything it is asked. A network board
//! authenticates every caller first and then asks [`NetworkPolicy`], which
//! admits enrolled principals (an agent, or a person signed in from a
//! browser) and refuses everyone else. That is the first of two layers: on
//! a network board the caller's grants and ceilings, in `http/access.rs`,
//! then decide what it may do in each board and channel.

use std::sync::Arc;

use openboard_api::{Actor, ActorKind};
use sha2::{Digest, Sha256};

use crate::chain::hex;

const ANONYMOUS_ID: &str = "anonymous";

/// Who is making a request. Established by the server, never by the client.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Principal {
    /// Stable principal ID.
    pub id: String,
    pub kind: ActorKind,
    /// Display handle, without any profile.
    pub handle: String,
}

impl Principal {
    /// The single unauthenticated principal of a local-mode server.
    pub fn local() -> Self {
        Self {
            id: "local".to_owned(),
            kind: ActorKind::Local,
            handle: "local".to_owned(),
        }
    }

    /// A caller the server has not authenticated. A network board uses it
    /// for the routes that take no token, the health check, enrolment,
    /// sign-in and the web UI's static files, and for nothing else. It
    /// never writes anything, and no agent or person can be given its
    /// handle.
    pub fn anonymous() -> Self {
        Self {
            id: ANONYMOUS_ID.to_owned(),
            kind: ActorKind::Service,
            handle: "anonymous".to_owned(),
        }
    }

    /// True for [`Principal::anonymous`]. IDs of enrolled principals are
    /// generated by the server and never equal this one.
    pub fn is_anonymous(&self) -> bool {
        self.id == ANONYMOUS_ID
    }

    /// The actor this principal writes as under an optional declared profile.
    ///
    /// The ID is derived from the principal ID and the profile alone, so the
    /// same pair always maps to the same actor.
    pub(crate) fn actor(&self, profile: Option<&str>) -> Actor {
        let mut hasher = Sha256::new();
        hasher.update(b"openboard.actor.v1\n");
        hasher.update(self.id.as_bytes());
        hasher.update(b"\n");
        if let Some(profile) = profile {
            hasher.update(b"profile\n");
            hasher.update(profile.as_bytes());
        }
        let digest = hex(&hasher.finalize());
        Actor {
            id: format!("act_{}", &digest[..24]),
            kind: self.kind,
            handle: match profile {
                Some(profile) => format!("{}/{profile}", self.handle),
                None => self.handle.clone(),
            },
            profile: profile.map(str::to_owned),
        }
    }
}

/// What the caller is trying to do.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Action {
    /// Read the server's health and version. Carries no board.
    Health,
    /// Read threads, messages, channel names or events.
    Read,
    /// Post a thread or a reply.
    Post,
    /// Create a channel by posting to a path that does not exist yet.
    CreateChannel,
    /// Create a board by using a name that does not exist yet.
    CreateBoard,
    /// Swap an enrolment code for a token. Carries no board. The caller is
    /// not authenticated yet; the code is what is checked.
    Enrol,
    /// Read or end the caller's own session: `whoami`, the web UI's session
    /// description and `logout`. Carries no board.
    Session,
    /// Swap a person's sign-in code for a browser session. Carries no
    /// board. The caller is not authenticated yet; the code is what is
    /// checked.
    SignIn,
    /// Replace the text of a message. The policy decides whether the caller
    /// may edit in the channel at all; that only the message's own author
    /// may do it is a fixed rule the server applies on top.
    Edit,
    /// Delete one's own message, leaving a tombstone.
    Delete,
    /// Delete a message someone else wrote (`delete`). On a local board
    /// there is no one else, so the server never grants it there.
    Moderate,
    /// Set or clear labels on a message.
    Label,
    /// Add or remove a reaction on a message.
    React,
    /// Fetch the web UI's page, script or style sheet. Carries no board.
    /// These files hold no board content, and the caller is not
    /// authenticated.
    Page,
    /// Create a task, or make a thread a task (`task.create`).
    CreateTask,
    /// Claim, renew, release and settle tasks (`task.claim`). Who holds a
    /// claim is a fixed rule the server applies on top.
    ClaimTask,
    /// Block, unblock, reopen, assign, change the needs of and cancel tasks
    /// the caller did not create (`task.manage`). The creator of a task needs
    /// no permission for these: that is a fixed rule.
    ManageTasks,
}

/// The outcome of an authorization check.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Decision {
    Allow,
    Deny,
}

impl Decision {
    pub fn is_allowed(self) -> bool {
        self == Decision::Allow
    }
}

/// The rules behind [`Authorizer::authorize`].
///
/// `board` is `None` only for actions that have no board. `channel` is `None`
/// when the action concerns the board as a whole, and otherwise the exact
/// path of one channel.
pub trait Policy: Send + Sync + 'static {
    fn decide(
        &self,
        principal: &Principal,
        action: Action,
        board: Option<&str>,
        channel: Option<&str>,
    ) -> Decision;
}

/// The M0 policy: the local principal holds `all`. Anyone else holds nothing.
#[derive(Debug, Clone, Copy, Default)]
pub struct LocalPolicy;

impl Policy for LocalPolicy {
    fn decide(
        &self,
        principal: &Principal,
        _action: Action,
        _board: Option<&str>,
        _channel: Option<&str>,
    ) -> Decision {
        if principal.kind == ActorKind::Local {
            Decision::Allow
        } else {
            Decision::Deny
        }
    }
}

/// The network policy: an unauthenticated caller may only check health,
/// enrol, sign in and fetch the web UI's static files, and an enrolled
/// principal passes on to its grants, which decide what it may do in each
/// board and channel (`crate::grants`).
#[derive(Debug, Clone, Copy, Default)]
pub struct NetworkPolicy;

impl Policy for NetworkPolicy {
    fn decide(
        &self,
        principal: &Principal,
        action: Action,
        _board: Option<&str>,
        _channel: Option<&str>,
    ) -> Decision {
        let allowed = if principal.is_anonymous() {
            matches!(
                action,
                Action::Health | Action::Enrol | Action::SignIn | Action::Page
            )
        } else {
            // The local principal does not exist on a network board. What
            // an enrolled principal may do in a board is decided by its
            // grants, on top of this.
            principal.kind != ActorKind::Local
        };
        if allowed {
            Decision::Allow
        } else {
            Decision::Deny
        }
    }
}

/// The single enforcement point. Cheap to clone.
#[derive(Clone)]
pub struct Authorizer {
    policy: Arc<dyn Policy>,
}

impl Authorizer {
    pub fn new(policy: Arc<dyn Policy>) -> Self {
        Self { policy }
    }

    /// Decides whether `principal` may perform `action` on `board` and,
    /// where one is given, on `channel`.
    pub fn authorize(
        &self,
        principal: &Principal,
        action: Action,
        board: Option<&str>,
        channel: Option<&str>,
    ) -> Decision {
        self.policy.decide(principal, action, board, channel)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const ACTIONS: [Action; 17] = [
        Action::Health,
        Action::Read,
        Action::Post,
        Action::CreateChannel,
        Action::CreateBoard,
        Action::Enrol,
        Action::Session,
        Action::SignIn,
        Action::Edit,
        Action::Delete,
        Action::Moderate,
        Action::Label,
        Action::React,
        Action::Page,
        Action::CreateTask,
        Action::ClaimTask,
        Action::ManageTasks,
    ];

    #[test]
    fn network_policy_admits_enrolled_principals_and_refuses_the_rest() {
        let authz = Authorizer::new(Arc::new(NetworkPolicy));
        let agent = Principal {
            id: "prn_1".into(),
            kind: ActorKind::Agent,
            handle: "builder".into(),
        };
        let person = Principal {
            id: "prn_2".into(),
            kind: ActorKind::Person,
            handle: "ada@example.com".into(),
        };
        for action in ACTIONS {
            for enrolled in [&agent, &person] {
                let decision = authz.authorize(enrolled, action, Some("general"), Some("a"));
                assert_eq!(decision, Decision::Allow, "{action:?}");
            }
            let decision = authz.authorize(&Principal::local(), action, Some("general"), None);
            assert_eq!(decision, Decision::Deny, "{action:?}");
            let anonymous = authz.authorize(&Principal::anonymous(), action, None, None);
            let open = matches!(
                action,
                Action::Health | Action::Enrol | Action::SignIn | Action::Page
            );
            assert_eq!(anonymous.is_allowed(), open, "{action:?}");
        }
    }

    #[test]
    fn local_principal_holds_all() {
        let authz = Authorizer::new(Arc::new(LocalPolicy));
        for action in ACTIONS {
            let decision = authz.authorize(&Principal::local(), action, Some("general"), Some("a"));
            assert_eq!(decision, Decision::Allow, "{action:?}");
        }
    }

    #[test]
    fn other_principals_hold_nothing() {
        let authz = Authorizer::new(Arc::new(LocalPolicy));
        let stranger = Principal {
            id: "svc_1".into(),
            kind: ActorKind::Service,
            handle: "ci".into(),
        };
        for action in ACTIONS {
            let decision = authz.authorize(&stranger, action, Some("general"), None);
            assert_eq!(decision, Decision::Deny, "{action:?}");
        }
    }

    #[test]
    fn actor_ids_are_stable_per_principal_and_profile() {
        let local = Principal::local();
        assert_eq!(local.actor(None), local.actor(None));
        assert_eq!(local.actor(Some("fx")), local.actor(Some("fx")));
        assert_ne!(local.actor(None).id, local.actor(Some("fx")).id);
        assert_ne!(local.actor(Some("fx")).id, local.actor(Some("fy")).id);
        assert_eq!(local.actor(None).handle, "local");
        assert_eq!(local.actor(Some("fx")).handle, "local/fx");
        assert_eq!(local.actor(Some("fx")).profile.as_deref(), Some("fx"));
    }
}
